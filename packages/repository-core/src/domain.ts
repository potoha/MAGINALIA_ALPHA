export const IDENTITY_PATH = ".maginalia/repository.json" as const;

export type RepositoryKind = "project" | "workbench" | "shelf";

export const REPOSITORY_KIND_LABELS: Readonly<Record<RepositoryKind, string>> = Object.freeze({
  project: "Project",
  workbench: "Workbench",
  shelf: "Private Shelf"
});

export interface RepositoryIdentity {
  readonly schemaVersion: 1;
  readonly id: string;
  readonly kind: RepositoryKind;
  readonly title: string;
  readonly templateVersion: 1;
}

export type RepositoryErrorCode =
  | "invalid-identity"
  | "invalid-id"
  | "invalid-kind"
  | "invalid-title";

/** A bounded, user-safe error shared by repository domain helpers. */
export class RepositoryError extends Error {
  public readonly userMessage: string;

  public constructor(public readonly code: RepositoryErrorCode, userMessage: string) {
    super(userMessage);
    this.name = "RepositoryError";
    this.userMessage = userMessage;
  }
}

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const REPOSITORY_KINDS = new Set<RepositoryKind>(["project", "workbench", "shelf"]);
const IDENTITY_KEYS = new Set(["schemaVersion", "id", "kind", "title", "templateVersion"]);

const INVALID_IDENTITY_MESSAGE = "The Project, Workbench, or Private Shelf identity is invalid.";
const INVALID_ID_MESSAGE = "The repository identity UUID is invalid.";
const INVALID_KIND_MESSAGE = "Choose Project, Workbench, or Private Shelf.";
const INVALID_TITLE_MESSAGE = "Enter a repository title (200 Unicode characters or fewer).";

function invalidIdentity(): never {
  throw new RepositoryError("invalid-identity", INVALID_IDENTITY_MESSAGE);
}

function isPlainRecord(value: unknown): value is Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
  try {
    // JSON.parse produces Object.prototype-backed records. Custom and class
    // prototypes are deliberately outside this portable contract.
    return Object.getPrototypeOf(value) === Object.prototype;
  } catch {
    return false;
  }
}

function isRepositoryKind(value: unknown): value is RepositoryKind {
  return typeof value === "string" && REPOSITORY_KINDS.has(value as RepositoryKind);
}

function isUuid(value: unknown): value is string {
  return typeof value === "string" && UUID_PATTERN.test(value);
}

function isTitle(value: unknown): value is string {
  return typeof value === "string"
    && value.length > 0
    && Array.from(value).length <= 200
    && value.trim().length > 0
    && !/[\u0000-\u001F\u007F-\u009F\u2028\u2029]/u.test(value);
}

/**
 * Validate and copy the portable identity. Only data properties on a normal
 * JSON object are accepted; accessors, symbols, and custom prototypes fail
 * closed before any field value is read.
 */
export function parseIdentity(value: unknown): RepositoryIdentity {
  if (!isPlainRecord(value)) return invalidIdentity();

  let keys: (string | symbol)[];
  try {
    keys = Reflect.ownKeys(value);
  } catch {
    return invalidIdentity();
  }
  if (keys.length !== IDENTITY_KEYS.size
    || keys.some((key) => typeof key !== "string" || !IDENTITY_KEYS.has(key))) {
    return invalidIdentity();
  }

  const values: Record<string, unknown> = {};
  try {
    for (const key of IDENTITY_KEYS) {
      const descriptor = Object.getOwnPropertyDescriptor(value, key);
      if (!descriptor || !("value" in descriptor)) return invalidIdentity();
      values[key] = descriptor.value;
    }
  } catch {
    return invalidIdentity();
  }

  if (values.schemaVersion !== 1 || values.templateVersion !== 1) return invalidIdentity();
  if (!isUuid(values.id) || !isRepositoryKind(values.kind) || !isTitle(values.title)) {
    return invalidIdentity();
  }

  return Object.freeze({
    schemaVersion: 1 as const,
    id: values.id,
    kind: values.kind,
    title: values.title,
    templateVersion: 1 as const
  });
}

/**
 * Construct an identity from a UUID generated by the host. UUID generation is
 * intentionally outside this package so the domain remains host-independent.
 */
export function createIdentity(
  kind: RepositoryKind,
  title: string,
  id: string
): RepositoryIdentity {
  if (!isRepositoryKind(kind)) {
    throw new RepositoryError("invalid-kind", INVALID_KIND_MESSAGE);
  }
  if (!isTitle(title)) {
    throw new RepositoryError("invalid-title", INVALID_TITLE_MESSAGE);
  }
  if (!isUuid(id)) {
    throw new RepositoryError("invalid-id", INVALID_ID_MESSAGE);
  }

  return parseIdentity({
    schemaVersion: 1,
    id,
    kind,
    title,
    templateVersion: 1
  });
}

export function isKnownRepositoryKind(value: unknown): value is RepositoryKind {
  return isRepositoryKind(value);
}

export function repositoryKindLabel(kind: RepositoryKind): string {
  return REPOSITORY_KIND_LABELS[kind];
}

/**
 * Build a portable technical name. It intentionally does not include the
 * human title, so renames and non-ASCII titles do not change storage identity.
 */
export function storageName(identity: RepositoryIdentity): string {
  const value = parseIdentity(identity);
  return "maginalia-" + value.kind + "-" + value.id.replaceAll("-", "").toLowerCase();
}
